"""Build a state-partitioned US place index from GeoNames' complete US extract.

Usage: python scripts/build-city-index.py /absolute/path/to/US.zip
Source: https://download.geonames.org/export/dump/US.zip (CC BY 4.0)
The original archive stays outside the site; only compact derived data is shipped.
"""
import datetime
import io
import json
# OFFLINE CITY DATA GENERATOR. Reads a local GeoNames archive and writes the
# state-partitioned place records used by lib/places.ts. A simulation does not
# download this archive. Coordinate lookup is separate from weather coverage.

from pathlib import Path
import re
import sys
import unicodedata
import zipfile

ROOT = Path(__file__).resolve().parents[1]
STATES = 'AL AK AZ AR CA CO CT DE DC FL GA HI ID IL IN IA KS KY LA ME MD MA MI MN MS MO MT NE NV NH NJ NM NY NC ND OH OK OR PA RI SC SD TN TX UT VT VA WA WV WI WY'.split()

def normalize(value):
    value = ''.join(c for c in unicodedata.normalize('NFD', value) if not unicodedata.combining(c)).lower()
    value = re.sub(r'^(city|town|village|borough|township) of\s+', '', value)
    for short, full in [('st', 'saint'), ('ft', 'fort'), ('mt', 'mount')]:
        value = re.sub(r'\b' + short + r'\.?\s+', full + ' ', value)
    return re.sub(r'[^a-z0-9]', '', value)

places = {state: [] for state in STATES}
municipalities = []
counties = {}
present = set()
with zipfile.ZipFile(sys.argv[1]) as archive:
    for line in io.TextIOWrapper(archive.open('US.txt'), encoding='utf-8'):
        r = line.rstrip('\n').split('\t')
        if len(r) < 19 or r[8] != 'US' or r[10] not in places:
            continue
        state, county, feature = r[10], r[11], r[7]
        if feature == 'ADM2':
            counties[(state, county)] = r[1]
        active_place = r[6] == 'P' and feature not in ('PPLH', 'PPLQ', 'PPLW')
        if not active_place and feature != 'ADM3':
            continue
        name = re.sub(r'^(City|Town|Village|Borough|Township) of\s+', '', r[1]) if feature == 'ADM3' else r[1]
        canonical = normalize(name)
        aliases = {normalize(v) for v in [r[1], r[2], *r[3].split(',')]}
        aliases.discard(canonical)
        aliases.discard('')
        aliases = sorted(a for a in aliases if len(a) <= 100)
        row = [int(r[0]), name, round(float(r[4]), 5), round(float(r[5]), 5), county, int(r[14] or 0), canonical, '|'.join(aliases)]
        if active_place:
            places[state].append(row)
            present.add((state, county, canonical))
        else:
            municipalities.append((state, county, canonical, row))

for state, county, canonical, row in municipalities:
    if (state, county, canonical) not in present:
        places[state].append(row)
        present.add((state, county, canonical))

out = ROOT / 'lib' / 'data' / 'places'
out.mkdir(parents=True, exist_ok=True)
for state, rows in places.items():
    rows.sort(key=lambda row: (-row[5], row[1], row[0]))
    for row in rows:
        row[4] = counties.get((state, row[4]), '')
    payload = json.dumps(rows, ensure_ascii=False, separators=(',', ':'))
    # String modules keep TypeScript from inferring hundreds of thousands of tuples.
    (out / f'{state}.ts').write_text('// Derived from GeoNames, CC BY 4.0. See NOTICE.md.\nexport default ' + json.dumps(payload, ensure_ascii=False) + ';\n')

loaders = '\n'.join(f'  {state}: () => import("./data/places/{state}"),' for state in STATES)
(ROOT / 'lib' / 'place-loaders.ts').write_text('// Generated by scripts/build-city-index.py\nexport const PLACE_LOADERS: Record<string, () => Promise<{ default: string }>> = {\n' + loaders + '\n};\n')
summary = {'source': 'https://download.geonames.org/export/dump/US.zip', 'retrieved': '2026-09-26', 'license': 'CC BY 4.0', 'places': sum(len(r) for r in places.values()), 'statesAndDC': len(places), 'counts': {k: len(v) for k,v in places.items()}}
(out / 'manifest.json').write_text(json.dumps(summary, indent=2) + '\n')
print(json.dumps({**{k:v for k,v in summary.items() if k != 'counts'}, 'bytes': sum(p.stat().st_size for p in out.glob('*.ts'))}))
